export function getProduct(productId) {
  return PRODUCTS.find((p) => p.product_id === productId) || null;
}

/**
 * Enforcement point for spec §2's registry integrity rules — the runtime
 * equivalent of the spec's "build fails on unknown/todo ProductLink" (this
 * codebase has no build step, so this is checked per-request instead).
 * @returns {{ ok: true, href: string, rel: string, product: object } | { ok: false, reason: string }}
 */
export function resolveProductLink(productId) {
  const product = getProduct(productId);
  if (!product) return { ok: false, reason: 'unknown_product' };
  if (product.status === 'todo') return { ok: false, reason: 'todo_not_promoted' };
  if (product.status === 'dead') return { ok: false, reason: 'dead_link' };
  const href = product.affiliate_url || product.url;
  if (!href) return { ok: false, reason: 'missing_url' };
  return { ok: true, href, rel: 'nofollow sponsored', product };
}

export function hasAnyAffiliateLink() {
  return PRODUCTS.some((p) => Boolean(p.affiliate_url));
}
